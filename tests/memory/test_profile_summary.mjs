import assert from 'node:assert/strict';
import {emptyProfileVault,addAnonymousProfile,appendScopedRecord} from '../../public-site/memory/profile-scope.mjs';
import {buildProfileSummary,buildProfileConsultText,FIELD_TITLES} from '../../public-site/memory/profile-summary.mjs';

const A='e4ad61f3-4cf2-40a8-a38c-1d098c91d643';
const B='e3c55b7d-26ba-4d56-9c78-2875b04f9079';
const C='f5e67a3b-15ef-4d59-bc7a-e864385cafb1';
const day='2026-11-12';
const record=(id,date,text,extras={})=>({id,date,text,...extras});
let vault=addAnonymousProfile(addAnonymousProfile(addAnonymousProfile(emptyProfileVault(),A),B),C);
vault=appendScopedRecord(vault,A,record('a-today-1',day,'A 가상 메모 첫째',{sleep:'나쁨',meal:'부족',question:'A만의 질문'}));
vault=appendScopedRecord(vault,A,record('a-today-2',day,'A 가상 메모 둘째',{sleep:'좋음'}));
vault=appendScopedRecord(vault,A,record('a-yesterday','2026-11-11','A 어제 메모',{medicationCheck:'확인 필요'}));
vault=appendScopedRecord(vault,A,record('a-older','2026-11-01','A 30일 이내 과거 메모',{meal:'보통'}));
vault=appendScopedRecord(vault,B,record('b-today',day,'B 가상 메모',{sleep:'보통',question:'B만의 비공개 질문'}));
vault=appendScopedRecord(vault,B,record('b-older','2026-10-01','B 30일 밖의 내용',{meal:'좋음'}));
const unassigned=record('unassigned','2026-11-12','누구에게도 배정하지 않은 기존 예시 기록');
vault={...vault,unassigned:[unassigned]};
const snapshot=JSON.stringify(vault);

const a7=buildProfileSummary(vault,A,7,day);
assert.equal(a7.periodDays,7);
assert.equal(a7.daily.length,7);
assert.equal(a7.startDate,'2026-11-06');
assert.equal(a7.endDate,day);
assert.equal(a7.storedCount,3);
assert.equal(a7.allStoredForProfile,4);
assert.equal(a7.observedDays,2);
assert.equal(a7.missingDays,5);
assert.equal(a7.questionCount,1);
assert.equal(a7.questions[0].text,'A만의 질문');
assert.equal(a7.daily[0].recordCount,2);
assert.equal(a7.daily[0].fields.sleep.kind,'multiple');
assert.match(a7.daily[0].fields.sleep.label,/복수 관찰/);
assert.equal(a7.daily[0].fields.meal.kind,'partial');
assert.match(a7.daily[0].fields.meal.label,/1건 항목 미기록/);
assert.equal(a7.daily[0].fields.medicationCheck.kind,'field-missing');
assert.equal(a7.daily[1].fields.sleep.kind,'field-missing');
assert.equal(a7.daily[2].fields.sleep.kind,'day-missing');
assert.equal(a7.daily[2].fields.sleep.label,'날짜 기록 없음');
assert.equal(a7.totals.sleep,2);
assert.equal(a7.totals.medicationCheck,1);
assert.ok(a7.records.every(x=>x.id.startsWith('a-')));
assert.ok(!JSON.stringify(a7).includes('B 가상 메모'));
assert.ok(!JSON.stringify(a7).includes('누구에게도 배정하지 않은'));

const a30=buildProfileSummary(vault,A,30,day);
assert.equal(a30.storedCount,4);
assert.equal(a30.observedDays,3);
assert.equal(a30.missingDays,27);
assert.equal(a30.daily.length,30);
assert.equal(a30.startDate,'2026-10-14');
const b7=buildProfileSummary(vault,B,7,day);
assert.equal(b7.storedCount,1);
assert.equal(b7.questions[0].text,'B만의 비공개 질문');
assert.equal(b7.missingDays,6);
assert.ok(!JSON.stringify(b7).includes('A만의 질문'));
assert.ok(!JSON.stringify(b7).includes('누구에게도 배정하지 않은'));
const b30=buildProfileSummary(vault,B,30,day);
assert.equal(b30.storedCount,1,'an out-of-range older record is excluded');
const c30=buildProfileSummary(vault,C,30,day);
assert.equal(c30.storedCount,0);
assert.equal(c30.missingDays,30);
assert.equal(c30.daily.every(x=>x.fields.sleep.kind==='day-missing'),true);
const textA=buildProfileConsultText(vault,A,30,day);
const textB=buildProfileConsultText(vault,B,30,day);
assert.match(textA,/A만의 질문/);
assert.doesNotMatch(textA,/B만의 비공개 질문|B 가상 메모|누구에게도 배정하지 않은/);
assert.match(textB,/B만의 비공개 질문/);
assert.doesNotMatch(textB,/A만의 질문|A 가상 메모/);
assert.match(textA,/보관 한도 20건/);
assert.match(textA,/기록이 없는 날짜의 건강 상태는 알 수 없습니다/);
assert.equal(Object.keys(FIELD_TITLES).length,3);
assert.throws(()=>buildProfileSummary(vault,undefined,7,day),/프로필 ID/);
assert.throws(()=>buildProfileSummary(vault,'ffffffff-ffff-4fff-bfff-ffffffffffff',7,day),/프로필을 찾을 수 없습니다/);
assert.throws(()=>buildProfileSummary(vault,A,14,day),/7일 또는 30일/);
assert.throws(()=>buildProfileSummary(vault,A,7,'2026-02-30'),/달력/);
assert.equal(buildProfileSummary(vault,C,7,'2024-03-01').startDate,'2024-02-24','leap-day arithmetic');
a7.records[0].text='수정 시도';
a7.daily[0].questions.push('변조 질문');
assert.equal(JSON.stringify(vault),snapshot,'summary returns copies, never mutates source');
console.log('PASS: two-profile 7/30-day isolation, day/field missing, same-day multiple observations, strict selector, leap date, copy-safe summary, unassigned exclusion');
