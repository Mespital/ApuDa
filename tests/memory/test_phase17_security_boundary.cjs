const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');

const live=read('public-site/memory/index.html');
const qa=read('public-site/memory/phase17-qa.html');
const secure=read('public-site/memory/scoped-secure-archive.mjs');
const tests=read('tests/memory/test_phase17_scoped_secure_archive.mjs');
const gates=JSON.parse(read('docs/qa/apuda-memory-release-gates.json'));
const script=qa.match(/<script type="module">([\s\S]*?)<\/script>/)?.[1];

assert.ok(script,'Phase 17 QA script exists');
assert.match(qa,/noindex,nofollow,noarchive/);
assert.match(qa,/실제 환자정보·개인 비밀번호를 입력하지 마세요/);
assert.match(script,/^const allowed=\/\^deploy-preview-/m);
assert.doesNotMatch(script,/\blocalStorage\s*[.[]|\bsessionStorage\s*[.[]|\bfetch\s*\(|\bXMLHttpRequest\s*\(/);
assert.doesNotMatch(secure,/\blocalStorage\s*[.[]|\bsessionStorage\s*[.[]|\bfetch\s*\(|\bXMLHttpRequest\s*\(/);
assert.ok(!live.includes('scoped-secure-archive.mjs'));
assert.ok(!live.includes('phase17-qa.html'));
assert.match(live,/const diaryKey = 'apuda-memory-care-diary-v1'/);
assert.match(secure,/APUDA-MEMORY-SCOPED-ARCHIVE-V1/);
assert.match(secure,/additionalData:encoder\.encode\(LABEL\)/);
assert.match(secure,/AES-256-GCM/);
assert.match(secure,/KDF_ITERATIONS/);
assert.match(secure,/output\.sourceProfileId!==expectedProfileId/);
assert.match(secure,/typeof expectedProfileId!=='string'/);
assert.match(secure,/MAX_ENVELOPE_BYTES=384\*1024/);
assert.match(secure,/MAX_PLAINTEXT_BYTES=256\*1024/);
assert.match(secure,/planProfileImport\(scratch,backup\.sourceProfileId,backup\)/);
assert.ok(!secure.includes('password:'),'never return/store password in backup');
assert.ok(!secure.includes('console.log'),'avoid private-data logging');
assert.match(tests,/node:crypto/);
assert.match(tests,/tamperedSalt/);
assert.match(tests,/tamperedIv/);
assert.match(tests,/emptyExport/);
assert.equal(gates.releaseDecision,'NO_GO');
assert.equal(gates.productionDeploymentAuthorized,false);
assert.ok(gates.tests.some(x=>x.id==='encrypted-backup-mobile'&&x.status==='PENDING'));
assert.ok(gates.tests.some(x=>x.id==='cross-device-restore'&&x.status==='DEFERRED'));
console.log('PASS: phase17 QA isolated, no live record access, encrypted envelope metadata and strict profile-binding gate; release NO_GO');
