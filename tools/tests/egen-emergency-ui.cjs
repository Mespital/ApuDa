// UI safety / accessibility contract checks for the ApuDa emergency finder.
// Run: node tools/tests/egen-emergency-ui.cjs
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const html=fs.readFileSync(path.resolve(__dirname,'../../public-site/emergency/index.html'),'utf8');
assert(html.includes('lang="ko"'));
assert(html.includes('name="viewport"'));
assert(html.includes('href="tel:119"'));
assert(html.includes('role="status" aria-live="polite"'));
assert(html.includes('id="stage1" name="stage1" required'));
assert(html.includes('id="stage2" name="stage2"'));
assert(html.includes('href="https://www.e-gen.or.kr/"'));
assert(html.includes('rel="noopener noreferrer"'));
assert(html.includes('prefers-reduced-motion:reduce'));
assert(html.includes('focus-visible'));
assert(html.includes('api') === false || !html.includes('EGEN_API_KEY'));
assert(html.includes('/.netlify/functions/egen-emergency?'));
assert(html.includes("payload.error==='not_configured'"));
assert(html.includes("Number.isInteger(beds)&&beds>=0"));
assert(html.includes('확정') && html.includes('119'));
assert(html.includes('results.replaceChildren()'));
assert(!html.includes('.innerHTML='),'API response must never be assigned to HTML');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length,'all ids must be unique');
assert(html.indexOf('href="tel:119"') < html.indexOf('id="search"'),'119 action must precede routine search');
assert(html.indexOf('id="search"') < html.indexOf('id="results"'),'search must precede results');
assert.equal((html.match(/<h1\b/g)||[]).length,1);
assert(html.includes('id="regionSearch"'),'regional search needs a discrete disclosure');
assert(html.includes('class="card region-card"'),'regional lookup remains available');
assert(!/<details[^>]*id="regionSearch"[^>]*\sopen(?:\s|>|=)/.test(html),'regional form should begin collapsed');
assert(html.includes('class="card nearby"'),'nearby search is the primary step');
assert(html.indexOf('href="tel:119"')<html.indexOf('class="card nearby"'),'emergency call must precede nearby search');
assert(html.indexOf('class="card nearby"')<html.indexOf('id="regionSearch"'),'nearby search must precede regional search');
// 2026-11-07: 사용자 요청으로 위치 권한 기반 주변 응급실 조회로 전환 — 개인정보 원칙을 계약으로 고정
assert(html.includes('id="nearbyBtn" type="button"'),'nearby lookup is an explicit button');
assert(/btn\.addEventListener\('click',[\s\S]*navigator\.geolocation\.getCurrentPosition/.test(html),'location is requested only after a click');
assert(!/^(?![\s\S]*addEventListener)[\s\S]*getCurrentPosition/.test(html.split('btn.addEventListener')[0]),'no location request on page load');
assert(!html.includes('watchPosition'),'no continuous tracking');
assert(html.includes('Math.round(pos.coords.latitude*1000)/1000'),'coordinates rounded to ~100m before leaving the device');
assert(!/localStorage|sessionStorage|indexedDB/.test(html),'location is never stored in the browser');
assert(html.includes('저장하거나 기록하지 않아요'),'privacy notice present');
assert(html.includes('err.code===1') && html.includes('openRegion()'),'denied permission falls back to regional search');
assert(html.includes('직선거리'),'distance is labelled as straight-line');
assert(html.includes('--brand:#115faa'),'ApuDa blue should be the central color token');
assert(html.includes('details.region-card>summary'),'regional summary has a scoped layout');
assert(html.includes('padding:24px 26px!important'),'desktop region card must have horizontal padding');
assert(html.includes('padding:19px 18px!important'),'mobile region card must have horizontal padding');
assert(html.includes('class="region-copy"'),'regional heading uses a shrinkable content cell');
assert(html.includes('class="region-mark"'),'regional heading uses a fixed-width icon cell');
assert(html.includes('class="region-arrow"'),'regional summary includes an end-aligned disclosure icon');
assert(html.includes('grid-template-columns:1fr;gap:16px'),'mobile form uses one column');
assert(html.includes('width:min(100%,776px)'),'desktop content width remains readable');

console.log('PASS: ApuDa emergency brand blue, responsive region padding, nearby-first (consented geolocation), privacy, 119 and API safe UI');
