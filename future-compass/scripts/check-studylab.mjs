import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import assert from 'node:assert/strict';

const root=path.resolve(path.dirname(new URL(import.meta.url).pathname),'..');
const load=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=load('dist/studylab.html');
const nav=load('dist/app-nav.js');
const sw=load('dist/sw.js');
const cmds=load('dist/study-commands.js');
const api=load('netlify/functions/studylab-generate.mjs');
const status=load('netlify/functions/studylab-status.mjs');
assert.match(html,/<title>AI 학습실 · 승준 공부관리 방<\/title>/);
assert.match(html,/pin-gate\.css/);
assert.match(html,/pin-gate\.js/);
assert.match(html,/study\.html#review/);
assert.match(html,/\.netlify\/functions\/studylab-generate/);
assert.match(html,/\.netlify\/functions\/studylab-status/);
assert.doesNotMatch(html,/\.netlify\/functions\/generate['"]/);
assert.doesNotMatch(html,/\.netlify\/functions\/status['"]/);
const inline=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)].map(m=>m[1]).filter(s=>s.trim());
assert.ok(inline.length>0,'no application script');
for(const s of inline)new vm.Script(s,{filename:'studylab inline'});
const cmdList=['cheatsheet','flashcards','mindmap','blueprint','quiz','explain5','keypoints','glossary','compare','recap','deepdive','examples','timeline','formula','mistakes','exam','teachback','studyplan','review','weakness'];
for(const cmd of cmdList)assert.ok(html.includes(cmd),'missing StudyLab command '+cmd);
assert.equal((nav.match(/studylab\.html/g)||[]).length,2,'both child and parent menus must link to StudyLab');
assert.match(cmds,/href="studylab\.html"/);
assert.match(sw,/"studylab\.html"/);
assert.match(sw,/'studylab\.html'/);
assert.match(api,/X-StudyLab-Code/);
assert.match(api,/OPENAI_API_KEY/);
assert.match(api,/STUDYLAB_ACCESS_CODE/);
assert.match(api,/store:false/);
assert.match(status,/ready:/);
console.log('PASS: StudyLab commands 20, PIN gate, navigation 2 roles, AI API route, JS syntax, SW cache, storage compatibility');
